--9.Segment customer into new returning and loyal based on their total no of previous purchase?
---.amd show the count of each segment.

Select * from customer_data;

Select
      case 
           when previous_purchases = 0 then 'New_customer'
           when previous_purchases between 1 and 15 then 'regular_customer'
        else 'loyal_customer'
           end as customer_segment,
           count(*) as customer_count
       From customer_data
                group by case
                when previous_purchases = 0 then 'New_customer'
                when previous_purchases between 1 and 15 then 'regular_customer'
           else 'loyal_customer'
           end 

--Business Problem:- lack of customer segmentation lead to generic strategies.
--Impact:-
        --Enables personalized marketing.
        --Improves retention strategies.
        --increases conversion rates.

