--8.Top 5 products with highest discount usage %.
Select * from customer_data;

Select top 5
      item_purchased,
      count(item_purchased) as total_no_of_item_sold,
      count(case when discount_applied = 'Yes' then 1 end) As no_of_times_when_sold,
      count(case when discount_applied = 'Yes' then 1 end) * 100.0 / Count(*) as discount_percent
From customer_data
group by item_purchased
order by  discount_percent desc;

--Business problem:- some product may be highly depend on discount.
--impact:-
        --identifies discount driven products.
        --helps optimize price strategy.
        --Reduces profit margin loss.
